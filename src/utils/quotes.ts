export function quoteForToday(lang: 'en' | 'zh-CN' | 'zh-TW'): string {
  const today = new Date();
  const seed = today.getFullYear() * 1000 + (today.getMonth() + 1) * 32 + today.getDate();
  const q = QUOTES[seed % QUOTES.length];
  if (lang === 'zh-CN') return q.zhCN;
  if (lang === 'zh-TW') return q.zhTW;
  return q.en;
}
